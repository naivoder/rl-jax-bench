"""Exact (tabular) analysis of the gridworlds for the toy checks (src/toys.py), built on OUR env (src/data.py): the
transition table is generated by vmapping data.step over every (state, action), so the exact numbers below test the
JAX environment itself.

  mdp_optimum          value iteration per hidden value (undiscounted return of the gamma-greedy policy, and V_gamma)
  pomdp_optimum        finite-horizon DP on the belief MDP (position, illum, set of hidden values still possible)
  occupancy / evaluate exact state occupancy (discounted or undiscounted visitation) and expected undiscounted return
  implicit_policy      pi_hat(a|b) = E_{d(s|b)} pi_theta(a|s)  (Thm 1)
  ail_fixed_point      iterate psi <- pi_hat under d^psi (Thm 2 / Lemma 2), from the uniform trainee
  exact_a2d            tabular A2D: exact expert policy gradient (Eq. 26) with a Q(b,a) critic or the state-
                       conditioned Monte-Carlo target (App. B.1 bias), trainee = exact AIL projection each iteration
Hidden-state conventions as data.py; observation id b(s) = pos (FL) or pos*3 + (illum ? 1 + h : 0) (TD, TD-k).
"""
from __future__ import annotations

from functools import lru_cache

import numpy as np
import jax
import jax.numpy as jnp

from . import data as D

H_MAX = D.MAX_STEPS


class Tab:
    """Tabular model of one env: S = n_pos * K * 2 states (pos, h, illum)."""

    def __init__(self, name: str):
        self.spec = spec = D.get_spec(name)
        self.n_pos, self.K = spec.n_pos, spec.K
        S = self.S = spec.n_pos * spec.K * 2
        pos = np.arange(S) // (spec.K * 2)
        h = (np.arange(S) // 2) % spec.K
        il = np.arange(S) % 2
        self.pos, self.h, self.il = pos, h, il
        st = D.EnvState(jnp.asarray(pos % spec.n), jnp.asarray(pos // spec.n), jnp.asarray(h, jnp.int32),
                        jnp.asarray(il.astype(bool)), jnp.zeros(S, jnp.int32))
        f = jax.vmap(lambda s, a: D.step(spec, s, a), in_axes=(0, None))
        nx, rw, tm = [], [], []
        for a in range(4):
            s2, r, d = jax.device_get(f(st, a))
            nx.append(np.asarray(s2.c) * spec.n + np.asarray(s2.r))
            rw.append(np.asarray(r)); tm.append(np.asarray(d))
            il2 = np.asarray(s2.illum).astype(int)
            nx[-1] = nx[-1] * spec.K * 2 + h * 2 + il2
        self.nxt = np.stack(nx, 1)            # (S, 4) next state index
        self.rew = np.stack(rw, 1).astype(np.float64)
        self.term = np.stack(tm, 1)           # goal / hazard (the time-out never fires at t = 0)
        r0, c0 = spec.start
        p0 = c0 * spec.n + r0
        self.d0 = np.zeros(S)
        for k in range(spec.K):
            self.d0[p0 * spec.K * 2 + k * 2] = 1.0 / spec.K
        if spec.kind == 'fl':
            self.obs = pos.copy()
            self.B = spec.n_pos
        else:
            self.obs = pos * 3 + np.where(il == 1, 1 + h, 0)
            self.B = spec.n_pos * 3
        self.floor_state = spec.floor.T.reshape(-1)[pos]       # pos index = c*n + r

    # ------------------------------------------------------------------ evaluation
    def behaviour(self, pi_l=None, pi_e=None, beta=0.0):
        if pi_e is None:
            return pi_l[self.obs]
        if pi_l is None:
            return pi_e
        return beta * pi_e + (1 - beta) * pi_l[self.obs]

    def occupancy(self, pi_s, gamma_w: float = 1.0, H: int = H_MAX):
        """sum_t w_t d_t(s) over t < H (d_t = prob. of being in s, alive, at step t); also E[undiscounted return]."""
        d = self.d0.copy()
        occ = np.zeros(self.S)
        ret = 0.0
        w = 1.0
        for t in range(H):
            occ += w * d
            ret += np.sum(d[:, None] * pi_s * self.rew)
            flow = d[:, None] * pi_s * (~self.term)
            d = np.zeros(self.S)
            np.add.at(d, self.nxt.reshape(-1), flow.reshape(-1))
            w *= gamma_w
        return occ, ret

    def q_values(self, pi_s, gamma: float, iters: int = 3000):
        """Discounted Q^pi(s, a) (time limit ignored)."""
        Q = np.zeros((self.S, 4))
        for _ in range(iters):
            V = np.sum(pi_s * Q, 1)
            Q = self.rew + gamma * (~self.term) * V[self.nxt]
        return Q

    def implicit_policy(self, pi_e, occ):
        num = np.zeros((self.B, 4))
        den = np.zeros(self.B)
        np.add.at(num, self.obs, occ[:, None] * pi_e)
        np.add.at(den, self.obs, occ)
        out = np.full((self.B, 4), 0.25)
        m = den > 0
        out[m] = num[m] / den[m, None]
        return out

    def kl_e_l(self, pi_e, pi_l, occ):
        q = pi_l[self.obs]
        m = pi_e > 0
        kl = np.where(m, pi_e * (np.log(np.where(m, pi_e, 1)) - np.log(np.maximum(q, 1e-300))), 0).sum(1)
        return float(np.sum(occ * kl) / np.sum(occ))

    # ------------------------------------------------------------------ optima
    def mdp_optimum(self, gamma: float = D.GAMMA):
        Q = np.zeros((self.S, 4))
        for _ in range(4000):
            Q = self.rew + gamma * (~self.term) * Q.max(1)[self.nxt]
        best = np.isclose(Q, Q.max(1, keepdims=True), atol=1e-7)
        pi = best / best.sum(1, keepdims=True)
        _, ret = self.occupancy(pi)
        return ret, float(np.sum(self.d0 * Q.max(1))), pi

    def pomdp_optimum(self, gamma: float = D.GAMMA, H: int = 40):
        spec, K = self.spec, self.K
        import sys
        sys.setrecursionlimit(100000)

        @lru_cache(maxsize=None)
        def V(t, p, il, alive):
            if t == H:
                return (0.0, 0.0)
            best = None
            for a in range(4):
                und = dis = 0.0
                groups = {}
                for k in alive:
                    s = p * K * 2 + k * 2 + il
                    r, s2, term = self.rew[s, a], self.nxt[s, a], self.term[s, a]
                    if term:
                        und += r / len(alive); dis += r / len(alive)
                        continue
                    p2, il2 = s2 // (K * 2), s2 % 2
                    if spec.kind == 'fl':
                        groups.setdefault((p2, il2, 'c'), []).append(k)
                    else:
                        groups.setdefault((p2, il2, k if il2 else 'c'), []).append(k)
                    und += r / len(alive); dis += r / len(alive)
                for (p2, il2, _), ks in groups.items():
                    fr = len(ks) / len(alive)
                    vu, vd = V(t + 1, p2, il2, frozenset(ks))
                    und += fr * vu; dis += fr * gamma * vd
                if best is None or dis > best[1] + 1e-12:
                    best = (und, dis)
            return best
        r0, c0 = spec.start
        return V(0, c0 * spec.n + r0, 0, frozenset(range(K)))

    # ------------------------------------------------------------------ AIL / A2D
    def ail_fixed_point(self, pi_e, iters: int = 60, gamma_w: float = 1.0):
        pi_l = np.full((self.B, 4), 0.25)
        for _ in range(iters):
            occ, _ = self.occupancy(self.behaviour(pi_l), gamma_w)
            pi_l = self.implicit_policy(pi_e, occ)
        occ, ret = self.occupancy(self.behaviour(pi_l), gamma_w)
        greedy = np.isclose(pi_l, pi_l.max(1, keepdims=True), atol=1e-9)
        greedy = greedy / greedy.sum(1, keepdims=True)
        _, ret_g = self.occupancy(self.behaviour(greedy))
        return {'ret_sto': ret, 'ret_greedy': ret_g, 'kl': self.kl_e_l(pi_e, pi_l, occ), 'pi_l': pi_l}

    def belief_q(self, pi_l, gamma: float):
        pi_s = self.behaviour(pi_l)
        Qs = self.q_values(pi_s, gamma)
        occ, _ = self.occupancy(pi_s, gamma)
        num = np.zeros((self.B, 4)); den = np.zeros(self.B)
        np.add.at(num, self.obs, occ[:, None] * Qs)
        np.add.at(den, self.obs, occ)
        Qb = np.where(den[:, None] > 0, num / np.maximum(den, 1e-300)[:, None], 0.0)
        return Qs, Qb, occ

    def exact_a2d(self, target: str = 'q', iters: int = 3000, lr: float = 0.05, gamma: float = D.GAMMA,
                  proj_gamma: float = 1.0):
        """Tabular A2D with beta = 0: expert logits z(s); each iteration (1) exact expert PG step (Eq. 26),
        grad_z(s, a) = d^psi(s) pi(a|s) (X(s,a) - sum_a' pi(a'|s) X(s,a')),
        X = Q^psi(b(s), a) ('q', learned-Q variant) or Q^psi(s, a) ('mc', the lambda = 1 Monte-Carlo target);
        (2) trainee <- implicit policy of the expert under the trainee's occupancy (exact AIL projection).
        Conventions: the PG step uses the gamma-discounted occupancy d^psi of Def. 1 / Eq. 3; the projection
        uses the occupancy discounted by proj_gamma, default 1 = uniform-in-time, which is what the practical AIL
        sampler draws (every visited state enters the buffer with equal weight). proj_gamma = gamma gives the
        Def.-1 projection; toy check (v) gives the same fixed points under both (scripts/exact_occupancy.py). The step
        z += 10 lr g / max|g| is a max-normalized (sign-like) step chosen for robust convergence of the exact
        iteration, not Eq. 26's step size; only the fixed point is compared."""
        z = np.zeros((self.S, 4))
        pi_l = np.full((self.B, 4), 0.25)
        hist = []
        for it in range(iters):
            pi_e = np.exp(z - z.max(1, keepdims=True)); pi_e /= pi_e.sum(1, keepdims=True)
            Qs, Qb, occ = self.belief_q(pi_l, gamma)
            X = Qb[self.obs] if target == 'q' else Qs
            dn = occ / occ.sum()
            g = dn[:, None] * pi_e * (X - np.sum(pi_e * X, 1, keepdims=True))
            z = z + lr * g / max(np.abs(g).max(), 1e-12) * 10.0
            pi_e = np.exp(z - z.max(1, keepdims=True)); pi_e /= pi_e.sum(1, keepdims=True)
            occ_u, _ = self.occupancy(self.behaviour(pi_l), proj_gamma)
            pi_l = self.implicit_policy(pi_e, occ_u)
            if it % 100 == 0 or it == iters - 1:
                occ_u, ret = self.occupancy(self.behaviour(pi_l))
                hist.append((it, ret, self.kl_e_l(pi_e, pi_l, occ_u)))
        return {'ret': hist[-1][1], 'kl': hist[-1][2], 'hist': hist}


def maxent_expert(tab: Tab, gamma: float = D.GAMMA):
    """Expert used by the toy checks: uniform over the Q*-optimal actions of the MDP."""
    return tab.mdp_optimum(gamma)[2]
