"""Write runs/<tag>/config.json FROM THE RUN ITSELF: the static block and each arm's resolved
config as stored in the lanes' metrics.json, plus run.json's argv. Never from agent.yaml defaults.

Usage: uv run python scripts/write_run_config.py full
"""
import glob
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(tag):
    out = {"source": "generated by scripts/write_run_config.py from runs/%s/<env>/seed_*/metrics.json" % tag, "envs": {}}
    for env_dir in sorted(glob.glob(os.path.join(REPO, "runs", tag, "*", ""))):
        files = sorted(glob.glob(os.path.join(env_dir, "seed_*", "metrics.json")))
        if not files:
            continue
        env = os.path.basename(os.path.normpath(env_dir))
        statics, arms, seeds = [], {}, []
        for f in files:
            m = json.load(open(f))
            statics.append(m["static"])
            for l in m["lanes"]:
                seeds.append(l["seed"])
                if l["arm"] in arms and arms[l["arm"]] != l["resolved_config"]:
                    raise ValueError(f"{env} arm {l['arm']}: resolved config differs between seeds")
                arms[l["arm"]] = l["resolved_config"]
        if any(s != statics[0] for s in statics):
            raise ValueError(f"{env}: static block differs between seed files")
        rj = os.path.join(env_dir, "run.json")
        argv = json.load(open(rj)).get("argv") if os.path.exists(rj) else None
        out["envs"][env] = {"static": statics[0], "seeds": sorted(set(seeds)), "arms": arms, "argv": argv}
    with open(os.path.join(REPO, "runs", tag, "config.json"), "w") as f:
        json.dump(out, f, indent=1)
    for e, v in out["envs"].items():
        print(e, "eval_episodes", v["static"]["eval_episodes"], "seeds", v["seeds"], "arms", len(v["arms"]))


if __name__ == "__main__":
    main(sys.argv[1])
