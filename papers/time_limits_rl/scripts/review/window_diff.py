"""Review: every E4 number under the old window (episodes ending after 0.9 x the NOMINAL 1e5 steps) vs the
corrected one (0.9 x the steps actually run, 98 304). Reads runs/full/report_pre_review.json (old) and report.json
(new, regenerated by scripts/full/report.py after the fix), the same for runs/oracle/ref_report*.json.
Usage: uv run python scripts/review/window_diff.py"""
import json, os
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
old = json.load(open(f"{R}/runs/full/report_pre_review.json"))["e4"]
new = json.load(open(f"{R}/runs/full/report.json"))["e4"]
def f(ms): return f"{ms[0]:.1f} ± {ms[1]:.1f}"
def pp(p): return f"{p['diff_mean']:+.1f} ± {p['diff_se']:.1f} ({p['wins']}/{p['n']}, p {p['t_p']:.2g})"
for blk in old:
    o, n = old[blk], new[blk]
    if not isinstance(o, dict) or "pairs" not in o:
        if isinstance(o, dict) and "diff_mean" in o:
            print(f"{blk:28s} OLD {pp(o)}  NEW {pp(n)}")
        elif isinstance(o, float):
            print(f"{blk:28s} OLD {o:.3g}  NEW {n:.3g}")
        continue
    for arm in o:
        if arm == "pairs":
            continue
        print(f"{blk:28s} {arm:16s} OLD {f(o[arm]['final'])}  NEW {f(n[arm]['final'])}")
    for k in o["pairs"]:
        print(f"{blk:28s} {k:32s} OLD {pp(o['pairs'][k])}  NEW {pp(n['pairs'][k])}")
for blk in ("ablation_vs_default",):
    pass
oo = json.load(open(f"{R}/runs/oracle/ref_report_pre_review.json"))
on = json.load(open(f"{R}/runs/oracle/ref_report.json"))
def walk(a, b, path=""):
    if isinstance(a, dict):
        for k in a:
            if k in b:
                walk(a[k], b[k], f"{path}.{k}")
    elif a != b and isinstance(a, (int, float, list)):
        print(f"ORACLE{path}: OLD {a}  NEW {b}")
walk(oo, on)
