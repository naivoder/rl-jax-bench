"""data.py -- ground truth and measurement generation (no dataset: the "data" is the authors' fixed truth array + simulated sensing).

* Truth: the authors' array data/truth_seed123546.npy [9 targets, 4 states, 200 steps] (NaN when not alive), regenerated with
  their generator and seed 123546; sha256 asserted at load; it reproduces all 16 count changes of Figure 3 (checked in the tests).
  The same truth is used for every run, algorithm, clutter rate and configuration (the paper uses one fixed truth).
* Measurements (paper SS V-A): each alive target is detected w.p. p_D and observed through H x + N(0, R); clutter is Poisson with
  rate lambda_C, uniform in the sensor FOV.  CFG-O replicates the code (D3, D6): constant p_D = 0.999, the NOISY measurement is
  deleted if it falls > 40 m from the sensor, clutter is drawn in the 80x80 square around the sensor and cropped to the disc
  (effective rate lambda_C pi/4).  CFG-P follows the text: eq. 48 on the true position (no truncation) and clutter in the disc.
* Randomness: all draws derive from jax.random keys supplied by the caller (key tree in src/algorithm.py); the draws of target t at
  step k for sensor s depend only on (run, k, s), so they are common random numbers across algorithms (policies) and clutter rates.
"""
from __future__ import annotations

import numpy as np
import jax
import jax.numpy as jnp

from src import model as M
from src.model import Cfg


def truth_arrays():
    """(truth[200, 9, 4], alive[200, 9], compact[200, K_TRUTH, 4], cmask[200, K_TRUTH]) as numpy float64 / bool."""
    T = M.load_truth()                                   # [9, 4, 200]
    alive = ~np.isnan(T[:, 0, :])                        # [9, 200]
    tr = np.transpose(T, (2, 0, 1)).copy()               # [200, 9, 4]
    al = alive.T.copy()                                  # [200, 9]
    tr = np.where(al[:, :, None], tr, 0.0)
    if al.sum(1).max() > M.K_TRUTH:
        raise RuntimeError("more simultaneously alive targets than K_TRUTH")
    comp = np.zeros((M.N_STEPS, M.K_TRUTH, 4))
    cm = np.zeros((M.N_STEPS, M.K_TRUTH), bool)
    for k in range(M.N_STEPS):
        ids = np.nonzero(al[k])[0]
        comp[k, : len(ids)] = tr[k, ids]
        cm[k, : len(ids)] = True
    return tr, al, comp, cm


def _compact_truth(tr, al):
    comp = np.zeros((M.N_STEPS, M.K_TRUTH, 4))
    cm = np.zeros((M.N_STEPS, M.K_TRUTH), bool)
    for k in range(M.N_STEPS):
        ids = np.nonzero(al[k])[0]
        comp[k, : len(ids)] = tr[k, ids]
        cm[k, : len(ids)] = True
    return comp, cm


def truth_set_arrays(path: str):
    """S-TRUTH sensitivity row: a stack of Kt independent truths generated by the authors' generator (scripts/official/gen_truths.py,
    scripts/build_strut.py).  Returns (tr[Kt,200,9,4], al[Kt,200,9], comp[Kt,200,K_TRUTH,4], cm[Kt,200,K_TRUTH]); run m uses truth m mod Kt."""
    z = np.load(path)
    outs = []
    for key in sorted(z.files, key=lambda k: int(k[len("truth"):])):
        T = z[key]                                       # [9, 4, 200], NaN when not alive
        alive = ~np.isnan(T[:, 0, :])
        tr = np.where(alive.T[:, :, None], np.transpose(T, (2, 0, 1)), 0.0)
        al = alive.T.copy()
        if al.sum(1).max() > M.K_TRUTH:
            raise RuntimeError("more simultaneously alive targets than K_TRUTH")
        comp, cm = _compact_truth(tr, al)
        outs.append((tr, al, comp, cm))
    return tuple(np.stack([o[i] for o in outs]) for i in range(4))


def count_changes(alive: np.ndarray):
    """Figure 3 check: list of (t, before, after) where the number of alive targets changes."""
    cnt = alive.sum(1)
    return [(k, int(cnt[k - 1]), int(cnt[k])) for k in range(1, len(cnt)) if cnt[k] != cnt[k - 1]]


def gen_measurements(key, truth_k, alive_k, spos, lam, cfg: Cfg):
    """One sensor's measurement set at one step.

    truth_k[9,4], alive_k[9] bool, spos[2], lam = clutter rate (traced scalar).  Returns (z[M_MEAS, 2], valid[M_MEAS], n_clutter_overflow).
    Slots 0..8 are the targets (valid when detected [and inside the FOV in CFG-O]); slots 9.. are clutter points.
    """
    kd, kn, kc, kp = jax.random.split(key, 4)
    u = jax.random.uniform(kd, (M.N_TRUTH,))
    noise = jnp.sqrt(cfg.R_var) * jax.random.normal(kn, (M.N_TRUTH, 2))
    tp = truth_k[:, M.POS_IDX]
    dist_true = jnp.sqrt(jnp.sum((tp - spos[None, :]) ** 2, axis=-1))
    z_t = tp + noise
    if cfg.truth_pd == "hard":
        det = alive_k & (u <= M.PD_MAX)
        dz = jnp.sqrt(jnp.sum((z_t - spos[None, :]) ** 2, axis=-1))
        det = det & (dz <= M.FOV)                       # official: measurement deleted if distance > 40 (sensor.py)
    else:
        pd = M.PD_MAX * jnp.exp(-0.5 * (dist_true / M.FOV) ** 2)
        det = alive_k & (u <= pd)
    nc = jax.random.poisson(kc, lam)
    over = nc > M.N_CLUT
    nc = jnp.minimum(nc, M.N_CLUT)
    if cfg.clutter_gen == "square":
        off = jax.random.uniform(kp, (M.N_CLUT, 2), minval=-1.0, maxval=1.0) * M.FOV
        z_c = spos[None, :] + off
        inside = jnp.sqrt(jnp.sum(off ** 2, axis=-1)) <= M.FOV      # official: delete if distance > 40
    else:
        k1, k2 = jax.random.split(kp)
        rad = M.FOV * jnp.sqrt(jax.random.uniform(k1, (M.N_CLUT,)))
        ang = 2 * jnp.pi * jax.random.uniform(k2, (M.N_CLUT,))
        z_c = spos[None, :] + jnp.stack([rad * jnp.cos(ang), rad * jnp.sin(ang)], axis=-1)
        inside = jnp.ones((M.N_CLUT,), bool)
    cv = (jnp.arange(M.N_CLUT) < nc) & inside
    z = jnp.concatenate([z_t, z_c], axis=0)
    valid = jnp.concatenate([det, cv], axis=0)
    return z, valid, over
